// Regenerates src/react/agents/metricsAppStores.js: the store links for the Cloudgate Metrics app and their QR
// codes as SVG path data, so the SDK needs no QR library at runtime and makes no request to draw them.
// Run only when a store link changes:  npm install --no-save qrcode && node scripts/generate-metrics-app-stores.mjs
import { writeFileSync } from 'node:fs';
import QRCode from 'qrcode';

const stores = [
  { id: 'google-play', label: 'Google Play', device: 'Android', url: 'https://play.google.com/store/apps/details?id=dev.cloudgate' },
  { id: 'app-store', label: 'iOS App Store', device: 'iPhone and iPad', url: 'https://apps.apple.com/us/app/cloudgate-metrics/id6755277714' },
  { id: 'app-gallery', label: 'AppGallery', device: 'Huawei', url: 'https://appgallery.huawei.com/app/C118146495' },
];

// One sub-path per horizontal run of dark modules.
const pathOf = ({ size, data }) => {
  let path = '';
  for (let y = 0; y < size; y++) for (let x = 0; x < size; x++) {
    if (!data[y * size + x]) continue;
    let end = x; while (end + 1 < size && data[y * size + end + 1]) end++;
    path += `M${x} ${y}h${end - x + 1}v1h-${end - x + 1}z`; x = end;
  }
  return path;
};

const items = stores.map(store => {
  const { modules } = QRCode.create(store.url, { errorCorrectionLevel: 'M' });
  return { ...store, size: modules.size, path: pathOf(modules) };
});
writeFileSync(new URL('../src/react/agents/metricsAppStores.js', import.meta.url),
  `// Generated by scripts/generate-metrics-app-stores.mjs. Do not edit: a changed link needs a new QR code.\n`
  + `// \`path\` draws the QR code for \`url\` on a \`size\` by \`size\` grid of modules.\n`
  + `export const METRICS_APP_STORES = ${JSON.stringify(items, null, 2)};\n`);
console.log(items.map(item => `${item.id}: ${item.size} modules`).join('\n'));
